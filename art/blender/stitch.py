# Builds art/blender/house_<country>.py from the shared house.py pipeline (materials, box helper,
# bake and export) and the country's geometry in parts/<country>_geometry.py.
#   python3 art/blender/stitch.py ph && /home/claude/bpy-env/bin/python art/blender/house_ph.py
import sys, os

c = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'house.py')).read()
head = src[:src.index("R = LAY['room']\nC = LAY['court']\nN = LAY['neighbour']\n\n# ---------------------------------------------------------------- ground and lawn")]
tail = src[src.index("# ---------------------------------------------------------------- join, unwrap, bake"):]
geo = open(os.path.join(here, 'parts', f'{c}_geometry.py')).read()
head = head.replace("'valora-house.glb'", f"'valora-house-{c}.glb'")
head = f"# GENERATED by art/blender/stitch.py {c}: edit house.py or parts/{c}_geometry.py instead.\n" + head
# the geometry part's extra materials refer to functions it defines: move them after those functions
a = geo.index("MATS.update({")
b = geo.index("})\n", a) + 3
mats, geo = geo[a:b], geo[:a] + geo[b:]
geo = geo.replace("def pole(a, b, r, mat", mats + "\n\ndef pole(a, b, r, mat", 1)
tail = tail.replace("""lawn = next(ob for ob, _ in parts if ob.name.startswith('lawn'))
roof = next(ob for ob, _ in parts if ob.name.startswith('roof'))
roof.hide_render = True
baked = [ob for ob, _ in parts if ob not in (lawn, roof)]""", "baked = [ob for ob, _ in parts]")
tail = tail.replace("house.name = 'valora-house'", f"house.name = 'valora-house-{c}'")
tail = tail.replace("'valora-colour.png'", f"'valora-{c}-colour.png'").replace("'valora-ao.png'", f"'valora-{c}-ao.png'")
tail = tail.replace("f.calc_center_median().z < 0.12]", "f.calc_center_median().z < 0.02]")
open(os.path.join(here, f'house_{c}.py'), 'w').write(head + geo + "\n" + tail)
print('wrote', f'house_{c}.py')
